"""The installer's v10 entry binds the reported candidate, the installed candidate 19 predecessor, the current stock
boot and the deployment name, and the identity gate covers v10. The installer itself is generated by the custodian."""
import pathlib
import re
import unittest

SOURCE = (pathlib.Path(__file__).resolve().parent.parent / 'prepare-installer.py').read_text()


class InstallerBindingTest(unittest.TestCase):
    def test_v10_entry(self):
        block = re.search(r"    'v10': \{(.*?)\n    \},", SOURCE, re.S).group(1)
        for key, value in (('candidate', '8d3289a10b7956d7fb55f4d74f0b1902f507cbadfdf6b20ebac654030df2d55f'),
                           ('manifest', '7e9a9e3642c98d0eb8c5f904c394538b2586654e63b9dbd88bd38a51a2fe6e17'),
                           ('predecessor', '5d9aa34b72cf3d8c86a53e7e000ec91f4478d52449c617c9e006f618232c560a'),
                           ('deployment', 'gemian-wifi-reference-deployment-10'),
                           ('boot_id', 'cf68b54a-7a3d-4949-8e1e-db1784cdc7df'), ('release', '3.18.41+')):
            self.assertIn("'%s': '%s'" % (key, value), block, key)

    def test_identity_gate_covers_v10(self):
        self.assertIn("args.revision in ('v3', 'v4', 'v5', 'v6', 'v7', 'v8', 'v9', 'v10')", SOURCE)

    def test_candidate_receipt_matches(self):
        import json
        receipt = json.loads((pathlib.Path(__file__).resolve().parent.parent / 'results/candidate-v10.json').read_text())
        self.assertEqual(receipt['boot2_sha256'], '8d3289a10b7956d7fb55f4d74f0b1902f507cbadfdf6b20ebac654030df2d55f')
        self.assertEqual(receipt['boot2_bytes'], 16777216)
        self.assertEqual(receipt['package_inventory_sha256'], 'bf72c7380e18bdb1403d2e76592cd8f526825c788b2a96a59f5998b48287031f')
        self.assertEqual(receipt['kernel_field_sha256'], '54723d29d382ca9321d6d7731aad596244f3499f911fdb9be3f73543a6cba7f2')


if __name__ == '__main__':
    unittest.main()
